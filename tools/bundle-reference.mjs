#!/usr/bin/env node
// Copy khata-standard reference datasets into index.html's bundled constants.
//
//   node tools/bundle-reference.mjs [--from ../khata-standard] [--check]
//
// Bahi ships its reference data inline so it works offline and on first run. Those constants are
// generated, not hand-edited: each sits between `// <ref:NAME>` and `// </ref:NAME>` markers, and
// this script rewrites the block from data/index.json's current file for that dataset. The REF
// table's version for the dataset is rewritten to match. --check exits 1 when a block differs from
// what khata-standard publishes, without writing.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const from = resolve(args.includes('--from') ? args[args.indexOf('--from') + 1] : resolve(here, '../../khata-standard'));
const check = args.includes('--check');
const appPath = resolve(here, '../index.html');

// dataset → [const name, REF key, how one row is written]
const BLOCKS = {
  'tds-sections': ['TDS_SECTIONS', 'tdsSections'],
  'tcs-sections': ['TCS_SECTIONS', 'tcsSections'],
  'gst-rates': ['GST_RATES', 'gstRates'],
};

const index = JSON.parse(readFileSync(resolve(from, 'data/index.json'), 'utf8'));
let html = readFileSync(appPath, 'utf8');
const drift = [];

for (const [name, [constName, refKey]] of Object.entries(BLOCKS)) {
  const meta = index.datasets[name];
  if (!meta || !meta.file) throw new Error(`${name}: not published in ${from}/data/index.json`);
  const doc = JSON.parse(readFileSync(resolve(from, 'data', name, meta.file), 'utf8'));
  const rows = doc.entries;
  if (!Array.isArray(rows)) throw new Error(`${name}: ${meta.file} has no entries array (schema ${doc.schema || 1})`);
  const body = [
    `// <ref:${name}> generated by tools/bundle-reference.mjs from khata-standard ${name}/${meta.file} (${meta.version}). Do not edit by hand.`,
    `const ${constName} = [`,
    ...rows.map((r) => '  ' + JSON.stringify(r) + ','),
    '];',
    `const ${constName}_VERSION = '${meta.version}';`,
    `// </ref:${name}>`,
  ].join('\n');
  const re = new RegExp(`// <ref:${name}>[\\s\\S]*?// </ref:${name}>`);
  if (!re.test(html)) throw new Error(`${name}: no // <ref:${name}> block in index.html`);
  const before = html.match(re)[0];
  if (before !== body) drift.push(name);
  html = html.replace(re, () => body);
  // The REF entry reads its version from the generated constant.
  const refRe = new RegExp(`(  ${refKey}:\\s*\\{ version: )[^,]+(, source: 'bundled', data: ${constName} \\})`);
  if (!refRe.test(html)) throw new Error(`REF.${refKey} is not of the form { version: …, source: 'bundled', data: ${constName} }`);
  html = html.replace(refRe, `$1${constName}_VERSION$2`);
}

if (check) {
  if (drift.length) { console.log(`bundled reference data differs from khata-standard: ${drift.join(', ')}`); process.exit(1); }
  console.log('bundled reference data matches khata-standard');
} else {
  writeFileSync(appPath, html);
  console.log(drift.length ? `updated: ${drift.join(', ')}` : 'already current');
}
